/**
 * The phone works out a flight's turbulence from its Flight Pack with a TypeScript port of the sampler and route
 * analyzer (frontend/src/fly). This test writes what the backend computes for fixed inputs to a fixture the frontend
 * tests compare the port against, and fails when the committed fixture no longer matches the backend. After a
 * deliberate change, regenerate it: `UPDATE_FIXTURES=1 ./sbtw "backend/testOnly *FlightPackParityTest"`.
 */
class FlightPackParityTest extends BaseTest with BackendSerialization {
  import FlightPackParityTest.*

  test("the frontend's parity fixture matches what the backend computes") {
    // Arrays on one line: the fixture stays a few thousand lines long and diffs stay readable.
    val json = fixture().printWith(Printer.spaces2.copy(lbracketRight = "", rbracketLeft = "", arrayCommaRight = " ")) +
      "\n"
    val file = repoRoot.resolve("frontend/src/fly/__tests__/fixtures/pack-parity.json")
    if (sys.env.contains("UPDATE_FIXTURES")) {
      Files.createDirectories(file.getParent)
      Files.writeString(file, json): Unit
    }
    withClue(s"$file is out of date: regenerate it (see FlightPackParityTest)") {
      Files.exists(file) shouldBe true
      Files.readString(file) shouldBe json
    }
  }

  private def fixture(): Json = {
    val rnd = new Random(42)
    Json.obj(
      "about" -> Json.fromString("Generated by FlightPackParityTest (backend). Do not edit by hand."),
      "geometry" -> geometry(rnd),
      "lambert" -> lambert(rnd),
      "sampler" -> sampler(rnd),
      "analyzer" -> analyzer()
    )
  }

  private def geometry(rnd: Random): Json = {
    val grid = PackGrid(jfk._1, jfk._2, lax._1, lax._2)
    val points = (0 until 40).map { k =>
      val (lat, lon) =
        if (k < 30) grid.pointAt(-60 + rnd.nextDouble() * (grid.totalKm + 120), -300 + rnd.nextDouble() * 600)
        else (25 + rnd.nextDouble() * 25, -125 + rnd.nextDouble() * 60)
      val (along, across) = grid.locate(lat, lon)
      Json.obj(
        "lat" -> num(lat),
        "lon" -> num(lon),
        "along" -> num(along),
        "cross" -> num(across),
        "cell" -> grid.cellOf(lat, lon).fold(Json.Null)((r, c) => Json.arr(Json.fromInt(r), Json.fromInt(c)))
      )
    }
    val centers = (0 until 12).map { _ =>
      val (row, col) = (rnd.nextInt(grid.rows), rnd.nextInt(grid.cols))
      val (lat, lon) = grid.cellCenter(row, col)
      Json.obj("row" -> Json.fromInt(row), "col" -> Json.fromInt(col), "lat" -> num(lat), "lon" -> num(lon))
    }
    Json.obj(
      "origin" -> Json.arr(num(jfk._1), num(jfk._2)),
      "destination" -> Json.arr(num(lax._1), num(lax._2)),
      "rows" -> Json.fromInt(grid.rows),
      "cols" -> Json.fromInt(grid.cols),
      "alongStepKm" -> num(grid.alongStepKm),
      "crossStepKm" -> num(grid.crossStepKm),
      "totalKm" -> num(grid.totalKm),
      "points" -> Json.fromValues(points),
      "centers" -> Json.fromValues(centers)
    )
  }

  private def lambert(rnd: Random): Json = {
    val random = (0 until 30).map(_ => (10 + rnd.nextDouble() * 50, -140 + rnd.nextDouble() * 90))
    val edges = Seq((-5.0, -100.0), (89.5, -100.0), (21.14, -122.72), (52.6, -61.0), (38.5, -97.5))
    Json.fromValues((random ++ edges).map { case (lat, lon) =>
      Json.obj("lat" -> num(lat), "lon" -> num(lon), "index" -> Json.fromInt(LambertGrid.nearestIndex(lat, lon)))
    })
  }

  /** A short route with spatially varying data: the port must find the same cell, level and frames as the backend. */
  private def sampler(rnd: Random): Json = {
    val grid = PackGrid(den._1, den._2, cos._1, cos._2, halfWidthKm = 30)
    val patterns = Vector.tabulate(3) { p =>
      Array.tabulate[Byte](LambertGrid.nx * LambertGrid.ny) { k =>
        val (i, j) = (k % LambertGrid.nx, k / LambertGrid.nx)
        if ((i * 7 + j * 3 + p * 11) % 97 == 0) EdrLayer.missing else (5 + (i * (3 + p) + j * (5 + 2 * p)) % 50).toByte
      }
    }
    def frame(kind: FrameKind, valid: Instant, issuedAt: Instant, fi: Int): EdrFrame =
      EdrFrame(
        kind,
        valid,
        issuedAt,
        SortedMap.from(FlightPack.levelsFt.zipWithIndex.map { case (level, li) =>
          level -> EdrLayer(level, ByteBuffer.wrap(patterns((fi + li) % 3)))
        })
      )
    val issued = Instant.parse("2026-01-15T12:00:00Z")
    val nowcastValid = issued.plus(45, ChronoUnit.MINUTES)
    val nowcast = frame(FrameKind.Nowcast, nowcastValid, nowcastValid, 0)
    val forecast = Range.inclusive(1, 3).map(h =>
      frame(FrameKind.Forecast, issued.plus(h.toLong, ChronoUnit.HOURS), issued, h)
    ).toVector
    val data = TurbulenceData(Some(nowcast), forecast)
    val manifest = PackEndpoint.manifest(
      grid,
      data,
      PackPoint(den._1, den._2),
      PackPoint(cos._1, cos._2),
      issued.plus(70, ChronoUnit.MINUTES),
      issued
    )
    val frames = (nowcast +: forecast).map(f => f.id -> f).toMap
    manifest.frames.size shouldBe 4
    manifest.frames.foreach { f => (f.rowStart, f.rowEnd) shouldBe (0, grid.rows) }
    val slabs = manifest.frames.map { f =>
      f.url -> Json.fromString(
        Base64.getEncoder.encodeToString(FlightPack.encode(grid, PackSlab(frames(f.id), f.rowStart, f.rowEnd)))
      )
    }
    val store = new TurbulenceStore
    val queries = (0 until 80).map { k =>
      val (row, col) = (rnd.nextInt(grid.rows), rnd.nextInt(grid.cols))
      val (lat, lon) = grid.cellCenter(row, col)
      val alt =
        if (k % 5 == 0) FlightPack.levelsFt(rnd.nextInt(FlightPack.levelsFt.size)).toDouble
        else 1000 + rnd.nextDouble() * 42000
      val time = issued.plusSeconds(30 * 60 + rnd.nextInt(210 * 60).toLong)
      val sample = store.sampleAt(data, LambertGrid.nearestIndex(lat, lon), alt, time)
      Json.obj(
        "lat" -> num(lat),
        "lon" -> num(lon),
        "row" -> Json.fromInt(row),
        "col" -> Json.fromInt(col),
        "altitudeFt" -> num(alt),
        "time" -> Json.fromLong(time.toEpochMilli),
        "edr" -> num(sample.edr),
        "source" -> Json.fromString(sample.source.toString)
      )
    }
    Json.obj("manifest" -> manifest.toJson, "slabs" -> Json.obj(slabs*), "queries" -> Json.fromValues(queries))
  }

  /** Horizontally uniform data that varies by level and frame: the port must analyse a flight exactly as the backend. */
  private def analyzer(): Json = {
    val issued = Instant.parse("2026-01-15T12:00:00Z")
    val nowcastValid = issued.plus(1, ChronoUnit.HOURS)
    val nowcastCodes = Vector(10, 12, 14, 16, 18, 20, 22, 24, 25, 23, 21, 19)
    val forecastCodes = Vector(
      Vector(8, 9, 10, 12, 14, 16, 18, 20, 21, 19, 17, 15),
      Vector(8, 9, 11, 13, 15, 18, 22, 26, 28, 27, 24, 255),
      Vector(9, 10, 12, 14, 16, 20, 24, 30, 33, 31, 28, 25)
    )
    val shared = mutable.Map.empty[Int, ByteBuffer]
    def uniform(kind: FrameKind, valid: Instant, issuedAt: Instant, codes: Vector[Int]): EdrFrame =
      EdrFrame(
        kind,
        valid,
        issuedAt,
        SortedMap.from(FlightPack.levelsFt.zip(codes).map { case (level, code) =>
          level -> EdrLayer(
            level,
            shared.getOrElseUpdate(code, ByteBuffer.wrap(Array.fill(LambertGrid.nx * LambertGrid.ny)(code.toByte)))
          )
        })
      )
    val nowcast = uniform(FrameKind.Nowcast, nowcastValid, nowcastValid, nowcastCodes)
    val forecast = forecastCodes.zipWithIndex.map { case (codes, h) =>
      uniform(FrameKind.Forecast, issued.plus(h + 1L, ChronoUnit.HOURS), issued, codes)
    }
    val store = new TurbulenceStore
    store.setNowcast(nowcast)
    store.setForecast(forecast)

    val gateToGate = RouteAnalyzer.analyzeFlight(
      store,
      ord._1,
      ord._2,
      den._1,
      den._2,
      issued.plus(80, ChronoUnit.MINUTES),
      None,
      AircraftClass.Medium
    )
    val heavyHigh = RouteAnalyzer.analyzeFlight(
      store,
      ord._1,
      ord._2,
      den._1,
      den._2,
      issued.plus(50, ChronoUnit.MINUTES),
      Some(37000),
      AircraftClass.Heavy
    )
    val now = issued.plus(125, ChronoUnit.MINUTES)
    val (lat, lon) = RouteAnalyzer.intermediate(ord._1, ord._2, den._1, den._2, 0.4)
    val remaining = RouteAnalyzer.analyzeRemaining(
      store,
      lat,
      lon,
      35000,
      Some(450.0),
      Some(260.0),
      Some(den),
      now,
      AircraftClass.Medium
    )
    val edrNow = Option(store.sample(lat, lon, 35000, now).edr).filterNot(_.isNaN)
    val upcoming = LiveFlightTracker.upcoming(remaining, edrNow, AircraftClass.Medium)

    Json.obj(
      "levelsFt" -> Json.fromValues(FlightPack.levelsFt.map(Json.fromInt)),
      "nowcast" -> Json.obj(
        "validTime" -> Json.fromLong(nowcastValid.toEpochMilli),
        "codes" -> Json.fromValues(nowcastCodes.map(Json.fromInt))
      ),
      "forecast" -> Json.fromValues(forecast.zip(forecastCodes).map { case (f, codes) =>
        Json.obj(
          "validTime" -> Json.fromLong(f.validTime.toEpochMilli),
          "issued" -> Json.fromLong(f.issued.toEpochMilli),
          "codes" -> Json.fromValues(codes.map(Json.fromInt))
        )
      }),
      "flights" -> Json.arr(
        Json.obj(
          "input" -> flightInput(ord, den, issued.plus(80, ChronoUnit.MINUTES), None, AircraftClass.Medium),
          "expected" -> analysisJson(gateToGate)
        ),
        Json.obj(
          "input" -> flightInput(ord, den, issued.plus(50, ChronoUnit.MINUTES), Some(37000), AircraftClass.Heavy),
          "expected" -> analysisJson(heavyHigh)
        )
      ),
      "remaining" -> Json.obj(
        "input" -> Json.obj(
          "lat" -> num(lat),
          "lon" -> num(lon),
          "altitudeFt" -> Json.fromInt(35000),
          "groundSpeedKts" -> num(450.0),
          "trackDeg" -> num(260.0),
          "destination" -> Json.arr(num(den._1), num(den._2)),
          "now" -> Json.fromLong(now.toEpochMilli),
          "aircraftClass" -> Json.fromString("Medium")
        ),
        "expected" -> analysisJson(remaining),
        "edrNow" -> edrNow.fold(Json.Null)(num),
        "upcoming" -> Json.obj(
          "headline" -> Json.fromString(upcoming.headline),
          "nowCategory" -> Json.fromString(upcoming.nowCategory.toString),
          "nextBumpCategory" -> upcoming.nextBumpCategory.fold(Json.Null)(c => Json.fromString(c.toString)),
          "nextBumpInMinutes" -> upcoming.nextBumpInMinutes.fold(Json.Null)(num),
          "nextBumpForMinutes" -> upcoming.nextBumpForMinutes.fold(Json.Null)(num),
          "worstNextHour" -> Json.fromString(upcoming.worstNextHour.toString)
        )
      )
    )
  }
}

object FlightPackParityTest {
  private val jfk = (40.6413, -73.7781)
  private val lax = (33.9416, -118.4085)
  private val ord = (41.9786, -87.9048)
  private val den = (39.8561, -104.6737)
  private val cos = (38.8058, -104.7008)

  private def num(d: Double): Json = if (d.isNaN) Json.Null else Json.fromDoubleOrNull(d)

  private def repoRoot: Path =
    Iterator
      .iterate(Paths.get("").toAbsolutePath)(_.getParent)
      .takeWhile(_ != null)
      .find(p => Files.isDirectory(p.resolve("turbol.spec")))
      .getOrElse(sys.error("can't find the repository root"))

  private def flightInput(
    from: (Double, Double),
    to: (Double, Double),
    departure: Instant,
    cruiseFt: Option[Int],
    aircraftClass: AircraftClass
  ): Json =
    Json.obj(
      "origin" -> Json.arr(num(from._1), num(from._2)),
      "destination" -> Json.arr(num(to._1), num(to._2)),
      "departure" -> Json.fromLong(departure.toEpochMilli),
      "cruiseFt" -> cruiseFt.fold(Json.Null)(Json.fromInt),
      "aircraftClass" -> Json.fromString(aircraftClass.toString)
    )

  private def analysisJson(a: RouteAnalysis): Json =
    Json.obj(
      "totalDistanceKm" -> num(a.totalDistanceKm),
      "durationMinutes" -> num(a.durationMinutes),
      "start" -> Json.fromLong(a.start.toEpochMilli),
      "cruiseAltitudeFt" -> Json.fromInt(a.cruiseAltitudeFt),
      "aircraftClass" -> Json.fromString(a.aircraftClass.toString),
      // lat, lon, km, altitudeFt, minutes, time, edr, category, source, nearGround
      "points" -> Json.fromValues(a.points.map { p =>
        Json.arr(
          num(p.lat),
          num(p.lon),
          num(p.distanceKm),
          Json.fromInt(p.altitudeFt),
          num(p.minutesFromStart),
          Json.fromLong(p.time.toEpochMilli),
          p.edr.fold(Json.Null)(num),
          Json.fromString(p.category.toString),
          Json.fromString(p.source.toString),
          Json.fromBoolean(p.nearGround)
        )
      }),
      "segments" -> Json.fromValues(a.segments.map(s =>
        Json.arr(Json.fromString(s.category.toString), num(s.startMinute), num(s.endMinute))
      )),
      "summary" -> Json.obj(
        "verdict" -> Json.fromString(a.summary.verdict),
        "worstCategory" -> Json.fromString(a.summary.worstCategory.toString),
        "maxEdr" -> a.summary.maxEdr.fold(Json.Null)(num),
        "worstMinute" -> a.summary.worstMinute.fold(Json.Null)(num),
        "worstLat" -> a.summary.worstLat.fold(Json.Null)(num),
        "worstLon" -> a.summary.worstLon.fold(Json.Null)(num),
        "minutesByCategory" -> Json.obj(a.summary.minutesByCategory.toSeq.sortBy(_._1).map { case (k, v) =>
          k -> num(v)
        }*),
        "percentByCategory" -> Json.obj(a.summary.percentByCategory.toSeq.sortBy(_._1).map { case (k, v) =>
          k -> num(v)
        }*),
        "coveragePercent" -> num(a.summary.coveragePercent),
        "notes" -> Json.fromValues(a.summary.notes.map(Json.fromString))
      ),
      "dataSources" -> Json.obj(
        "nowcastValid" -> a.dataSources.nowcastValid.fold(Json.Null)(t => Json.fromLong(t.toEpochMilli)),
        "forecastIssued" -> a.dataSources.forecastIssued.fold(Json.Null)(t => Json.fromLong(t.toEpochMilli)),
        "forecastUntil" -> a.dataSources.forecastUntil.fold(Json.Null)(t => Json.fromLong(t.toEpochMilli))
      )
    )
}
